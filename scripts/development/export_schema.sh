#!/usr/bin/env bash
# Exports the current MySQL DDL to database/schema/schema.sql for review.
# Alembic migrations remain the source of truth; this file is a generated
# snapshot so the schema can be read without running the application.
#
# The dump is written to a temporary file and moved into place only when
# mysqldump succeeds, so a failed export never empties the committed snapshot.
set -euo pipefail
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
env_file="${repo_root}/.env"
if [[ ! -f "${env_file}" ]]; then
  echo "Missing ${env_file}. Copy .env.example to .env and set the MySQL values first." >&2
  exit 1
fi
set -a; source "${env_file}"; set +a
out="${repo_root}/database/schema/schema.sql"
tmp="$(mktemp "${out}.XXXXXX")"
trap 'rm -f "${tmp}"' EXIT
if ! {
  echo "-- Generated by scripts/development/export_schema.sh from the migrated database."
  echo "-- Source of truth: backend/migrations/versions/. Do not edit by hand."
  mysqldump --no-defaults --host="${MYSQL_HOST}" --port="${MYSQL_PORT}" --protocol=tcp \
    --user="${MYSQL_USER}" --password="${MYSQL_PASSWORD}" \
    --no-data --skip-comments --skip-add-drop-table --compact --skip-lock-tables --no-tablespaces "${MYSQL_DATABASE}" \
    | sed -e 's/ AUTO_INCREMENT=[0-9]*//' -e 's/^\/\*!.*\*\/;$//' | grep -v '^$'
} > "${tmp}"; then
  echo "mysqldump failed; ${out} was left unchanged." >&2
  exit 1
fi
mv "${tmp}" "${out}"
echo "wrote ${out}"
