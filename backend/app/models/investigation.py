from datetime import datetime
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    JSON,
    CheckConstraint,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base
from app.models.enums import AlertType, InvestigationStatus, Severity

if TYPE_CHECKING:
    from app.models.production import ProductionBatch


class Alert(Base):
    """A notification for the dashboard; audit rows that outlive what they reference.

    ``machine_id`` is set by the simulation and the batch quarantine;
    ``production_order_id`` is set by the ORDER_OVERDUE check, which also uses
    it to find the open alert for an order. Both are SET NULL on delete.
    """

    __tablename__ = "alerts"
    __table_args__ = (
        Index("ix_alerts_created", "created_at", "id"),
        Index("ix_alerts_production_order", "production_order_id"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    machine_id: Mapped[int | None] = mapped_column(ForeignKey("machines.id", ondelete="SET NULL"))
    production_order_id: Mapped[int | None] = mapped_column(
        ForeignKey("production_orders.id", ondelete="SET NULL", name="fk_alerts_production_order")
    )
    alert_type: Mapped[AlertType] = mapped_column(
        Enum(AlertType, name="alert_type"), nullable=False
    )
    severity: Mapped[Severity] = mapped_column(Enum(Severity, name="severity"), nullable=False)
    message: Mapped[str] = mapped_column(String(255), nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), nullable=False
    )
    acknowledged_at: Mapped[datetime | None] = mapped_column(DateTime)
    acknowledged_by: Mapped[int | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))


class Investigation(Base):
    """A quality investigation scoped to a time window and optionally a machine.

    The summary is generated by the rule engine; the conclusion is written by
    an engineer when the investigation is closed. Both are kept so reviewers
    can compare what the system proposed with what a person decided.
    """

    __tablename__ = "investigations"
    __table_args__ = (
        CheckConstraint("window_end > window_start", name="ck_investigation_window_order"),
        CheckConstraint(
            "(status = 'CLOSED') = (closed_at IS NOT NULL)", name="ck_investigation_closed"
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    title: Mapped[str] = mapped_column(String(150), nullable=False)
    machine_id: Mapped[int | None] = mapped_column(ForeignKey("machines.id", ondelete="SET NULL"))
    product_id: Mapped[int | None] = mapped_column(ForeignKey("products.id", ondelete="SET NULL"))
    window_start: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    window_end: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    status: Mapped[InvestigationStatus] = mapped_column(
        Enum(InvestigationStatus, name="investigation_status"),
        nullable=False,
        default=InvestigationStatus.OPEN,
    )
    summary: Mapped[str | None] = mapped_column(Text)
    conclusion: Mapped[str | None] = mapped_column(Text)
    opened_by: Mapped[int | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    created_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), nullable=False
    )
    closed_at: Mapped[datetime | None] = mapped_column(DateTime)

    evidence: Mapped[list["InvestigationEvidence"]] = relationship(
        back_populates="investigation",
        cascade="all, delete-orphan",
        order_by="InvestigationEvidence.sequence",
    )
    batch_links: Mapped[list["InvestigationBatch"]] = relationship(
        back_populates="investigation", cascade="all, delete-orphan"
    )


class InvestigationEvidence(Base):
    """One evidence card on the investigation case board.

    Each card stores the exact SQL that produced it and the result rows, so
    the user interface can show the query behind every finding. The rows are
    stored as JSON because the shape differs per rule.
    """

    __tablename__ = "investigation_evidence"
    __table_args__ = (
        UniqueConstraint("investigation_id", "sequence", name="uq_evidence_investigation_sequence"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    investigation_id: Mapped[int] = mapped_column(
        ForeignKey("investigations.id", ondelete="CASCADE"), nullable=False
    )
    sequence: Mapped[int] = mapped_column(Integer, nullable=False)
    rule_code: Mapped[str] = mapped_column(String(40), nullable=False)
    title: Mapped[str] = mapped_column(String(150), nullable=False)
    narrative: Mapped[str] = mapped_column(Text, nullable=False)
    query_name: Mapped[str] = mapped_column(String(60), nullable=False)
    query_sql: Mapped[str] = mapped_column(Text, nullable=False)
    # {"columns": [...], "rows": [[...], ...]}; see investigation_service.evidence_payload.
    result_rows: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), nullable=False
    )

    investigation: Mapped[Investigation] = relationship(back_populates="evidence")


class InvestigationBatch(Base):
    """Junction table: batches flagged by an investigation (many-to-many)."""

    __tablename__ = "investigation_batches"

    investigation_id: Mapped[int] = mapped_column(
        ForeignKey("investigations.id", ondelete="CASCADE"), primary_key=True
    )
    batch_id: Mapped[int] = mapped_column(
        ForeignKey("production_batches.id", ondelete="RESTRICT"), primary_key=True
    )
    reason: Mapped[str] = mapped_column(String(255), nullable=False)

    investigation: Mapped[Investigation] = relationship(back_populates="batch_links")
    batch: Mapped["ProductionBatch"] = relationship()
